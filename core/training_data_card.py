"""
SimAPI — Training Data Card.

A machine-generated audit document that travels WITH a dataset. Where the
JSON response is for machines (CI, pipelines), the card is for the human who
six months later asks: "this policy was trained in March — what data was it
trained on, what did the validator say, what was removed and why, and what
are the known blind spots?"

Provenance documentation of this kind is increasingly a procurement and
compliance requirement (EU AI Act Art. 10 data-governance expectations,
model cards, datasheets for datasets). The card is deliberately deterministic:
the same validation result always renders the same markdown, byte for byte,
so it can be committed next to the dataset and diffed in review.

Rendered from the public ``/v1/validate`` response dict only — no engine
internals, no clock, no randomness.
"""
from __future__ import annotations

from typing import Any

CARD_VERSION = "1.0"
ENGINE_VERSION = "3.1.0"


def _g(result: dict[str, Any], key: str, default: Any = None) -> Any:
    v = result.get(key, default)
    return default if v is None else v


def _pct(x: float) -> str:
    return f"{100.0 * float(x):.1f}%"


def build_training_data_card(result: dict[str, Any], *, dataset_name: str = "") -> str:
    """Render a validation report as a markdown Training Data Card."""
    prov = _g(result, "provenance", {}) or {}
    exclusions = _g(result, "exclusions", []) or []
    issues = _g(result, "issues", []) or []
    sd = _g(result, "surface_diagnostics", {}) or {}
    demoted = sd.get("demoted_targets", []) or []
    job_id = str(_g(result, "job_id", "unknown"))
    status = str(_g(result, "status", "unknown"))
    n_rows = int(_g(result, "trials_submitted", 0) or 0)
    n_excl = int(_g(result, "trials_excluded", 0) or 0)
    excl_rate = float(_g(result, "exclusion_rate", 0.0) or 0.0)
    training_ready = bool(_g(result, "training_ready", False))

    status_text = {
        "passed": "PASSED — no physically invalid rows detected",
        "warning": "WARNING — findings need review or training suitability is limited",
        "failed": "FAILED — one or more validation checks failed",
    }.get(status, status.upper())

    lines: list[str] = []
    title = f"Training Data Card: {dataset_name}" if dataset_name else "Training Data Card"
    lines.append(f"# {title}")
    lines.append("")
    lines.append(f"Generated by SimAPI v{ENGINE_VERSION} (card format v{CARD_VERSION}). "
                 f"This document is deterministic — re-running validation on identical data "
                 f"reproduces it byte-for-byte, so it can be committed alongside the dataset "
                 f"and reviewed in diffs.")
    lines.append("")

    # ── Verdict ──────────────────────────────────────────────────────────
    lines.append("## Validation verdict")
    lines.append("")
    lines.append(f"- **Verdict:** {status_text}")
    lines.append(f"- **Training-ready:** {'yes' if training_ready else 'no'}")
    lines.append(f"- **Rows:** {n_rows} submitted, {n_rows - n_excl} retained, {n_excl} excluded "
                 f"({_pct(excl_rate)} exclusion rate)")
    lines.append(f"- **Validation profile:** {_g(result, 'profile', 'default')}")
    domain = result.get("domain") or result.get("simulation_type") or "unspecified"
    lines.append(f"- **Domain:** {domain}")
    lines.append(f"- **Job ID:** `{job_id}`")
    lines.append("")

    # ── What ran ─────────────────────────────────────────────────────────
    lines.append("## What was checked")
    lines.append("")
    n_laws = prov.get("n_laws_confirmed", 0)
    n_anch = prov.get("n_anchored_constants", 0)
    engines = [
        "Dimensional-analysis engine: unit resolution, Pi-group discovery, "
        f"anchored physical constants ({n_anch} confirmed), discovered laws ({n_laws} confirmed)",
        "APIE engine: episode-aware row-level corruption screening and temporal coherence",
        "Robotics suite: configured signal limits, trajectory timing, and "
        "finite-difference motion checks when the required columns are present",
        "Training-suitability analysis: coverage, imbalance, leakage",
    ]
    for e in engines:
        lines.append(f"- {e}")
    lines.append("")

    # ── Exclusions ───────────────────────────────────────────────────────
    lines.append("## Exclusions")
    lines.append("")
    if exclusions:
        by_reason: dict[str, int] = {}
        for e in exclusions:
            reason = str(e.get("reason", "unspecified"))
            by_reason[reason] = by_reason.get(reason, 0) + 1
        lines.append(f"{n_excl} row(s) were excluded from training by the validator:")
        lines.append("")
        for reason, count in sorted(by_reason.items(), key=lambda kv: -kv[1]):
            lines.append(f"- {count} row(s): {reason}")
        idx = [int(e.get("trial_index", -1)) for e in exclusions[:50]]
        idx_s = ", ".join(str(i) for i in idx)
        more = " ..." if n_excl > 50 else ""
        lines.append("")
        lines.append(f"Excluded row indices (first {min(50, n_excl)}): {idx_s}{more}")
    else:
        lines.append("No rows were excluded — every submitted row passed the physical-validity checks.")
    lines.append("")

    # ── Flags for review ─────────────────────────────────────────────────
    review = [i for i in issues if str(i.get("status", "")) == "warning"]
    if review:
        lines.append("## Flagged for human review (not auto-excluded)")
        lines.append("")
        for i in review[:10]:
            lines.append(f"- **{i.get('human_name') or i.get('name', 'check')}** — "
                         f"{i.get('description', '')}")
        if len(review) > 10:
            lines.append(f"- ... and {len(review) - 10} more warning(s)")
        lines.append("")

    # ── Known limitations / self-demotion ────────────────────────────────
    lines.append("## Known limitations of this validation")
    lines.append("")
    limitations: list[str] = []
    if demoted:
        for finding in demoted:
            column = str(finding.get("column", "unknown"))
            gate = str(finding.get("gate", "surface_signal_check"))
            reason = str(finding.get("reason", "the available data did not support this model"))
            limitations.append(
                f"The response-surface model was **not applied** to `{column}` "
                f"(gate: {gate}): {reason}. Rows were not flagged from this model."
            )
    else:
        limitations.append(
            "Gradual sensor drift *within* a single frame cannot be detected per-sample: "
            "a slowly drifting value is physically plausible at every individual timestep. "
            "Cross-run history (config_key baselining) catches it over successive runs.")
    limitations.append(
        "Detection quality depends on column semantics: columns the unit resolver "
        "could not classify with confidence are excluded from law discovery.")
    for s in limitations:
        lines.append(f"- {s}")
    lines.append("")

    # ── Checks inventory ─────────────────────────────────────────────────
    cats = _g(result, "checks_by_category", {}) or {}
    if cats:
        lines.append("## Checks executed")
        lines.append("")
        lines.append("| Category | Checks |")
        lines.append("|---|---|")
        for cat, n in sorted(cats.items()):
            lines.append(f"| {cat} | {n} |")
        lines.append("")

    lines.append("## Reproducibility")
    lines.append("")
    lines.append("```bash")
    lines.append("# Re-run validation and regenerate this card:")
    lines.append("curl -X POST $SIMAPI_URL/v1/validate/report \\")
    lines.append("  -H 'Content-Type: application/json' \\")
    lines.append("  -d '{\"data\": <same rows>, \"format\": \"card\"}' > training_data_card.md")
    lines.append("```")
    lines.append("")
    return "\n".join(lines)
